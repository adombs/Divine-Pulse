"""Small capabilities used by application operations.

These protocols describe what an operation needs, not how JSON, FastAPI, or the
emulator implements it.
"""

from __future__ import annotations

from collections.abc import Collection, Mapping
from typing import Any, Protocol
from pathlib import Path

from ..domain.battle import Battle
from ..domain.ebst import EbstConfig
from ..domain.runs import Run, RunSummary
from ..domain.units import Unit


class MissingRecord(Exception):
    """An expected missing run, unit, or battle reported by a repository."""


class RunRepository(Protocol):
    def list(self) -> list[RunSummary]: ...
    def get(self, run_id: str) -> Run: ...
    def save(self, run: Run) -> None: ...
    def create(self, name: str) -> Run: ...
    def rename(self, run_id: str, name: str) -> Run: ...
    def delete(self, run_id: str) -> None: ...
    def put_unit(self, run_id: str, key: str, unit: Unit) -> None: ...
    def apply_units(self, run_id: str, units: Mapping[str, Unit | None]) -> None: ...
    def set_ebst(self, run_id: str, config: EbstConfig) -> None: ...
    def unit_scores(self, run_id: str) -> dict[str, int]: ...


class BattleRepository(Protocol):
    def list(self, run_id: str) -> list[Battle]: ...
    def replace(self, run_id: str, battles: list[Battle]) -> None: ...
    def extend(self, run_id: str, battles: list[Battle]) -> None: ...
    def delete(self, run_id: str, battle_id: str) -> None: ...
    def delete_run(self, run_id: str) -> None: ...
    def add(self, battle: Battle) -> None: ...
    def discard(self, run_id: str, ids: Collection[str]) -> list[str]: ...
    def restore(self, run_id: str, ids: Collection[str]) -> list[str]: ...


class SettingsValues(Protocol):
    active_run_id: str | None
    window_mode: str
    check_updates: bool

    def model_dump(self) -> dict[str, Any]: ...


class SettingsRepository(Protocol):
    def get(self) -> SettingsValues: ...
    def update(self, **changes: Any) -> SettingsValues: ...


class EventPublisher(Protocol):
    def publish(self, event: str, data: Any = None) -> None: ...


class UpdateChecks(Protocol):
    def status(self) -> dict[str, Any]: ...
    def settings_changed(self) -> None: ...


class ScannerOperations(Protocol):
    def current_battle(self) -> Battle | None: ...
    def auto_status(self) -> dict[str, Any]: ...
    def settings_changed(self) -> None: ...


class WindowOperations(Protocol):
    def show(self) -> None: ...
    def set_mode(self, mode: str) -> None: ...


class GameMemoryCheck(Protocol):
    def check(self) -> dict[str, Any]: ...


class SystemInformation(Protocol):
    def open_folder(self, folder: Path) -> None: ...
